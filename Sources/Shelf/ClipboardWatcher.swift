import AppKit
import ImageIO
import UniformTypeIdentifiers
import Darwin

/// A read-only source, injected in tests so they never access the user's clipboard.
@MainActor
protocol ClipboardSource {
    var changeCount: Int { get }
    var itemTypes: [[NSPasteboard.PasteboardType]] { get }
    func data(forType type: NSPasteboard.PasteboardType, at index: Int) -> Data?
}

@MainActor
struct SystemClipboardSource: ClipboardSource {
    // Access is lazy: constructing a disabled watcher does not read the pasteboard.
    var changeCount: Int { NSPasteboard.general.changeCount }
    var itemTypes: [[NSPasteboard.PasteboardType]] {
        (NSPasteboard.general.pasteboardItems ?? []).map(\.types)
    }
    func data(forType type: NSPasteboard.PasteboardType, at index: Int) -> Data? {
        guard let items = NSPasteboard.general.pasteboardItems, items.indices.contains(index) else { return nil }
        return items[index].data(forType: type)
    }
}

/// The application a copy came from. The bundle identifier is the identity;
/// the name is the label that application had when the copy was observed.
struct SourceApp: Codable, Equatable, Hashable {
    let bundleID: String
    var name: String
}

enum ClipboardAdmissionDecision: Equatable {
    case rejected
    case admitted(SourceApp?)
}

/// Pause, skip-next, per-app exclusion and source attribution. Image, text
/// and link capture consult one object through `ClipboardWatcher.admission`.
@MainActor
protocol ClipboardAdmission: AnyObject {
    /// While true a watcher advances past every change without reading it.
    var isPaused: Bool { get }
    /// True when this change is the one copy the user asked to skip. Both
    /// watchers observe the same change count and get the same answer.
    func skips(changeCount: Int) -> Bool
    /// Called only for a copy without private markers.
    func admit(source: any ClipboardSource, items: [[NSPasteboard.PasteboardType]]) -> ClipboardAdmissionDecision
}

/// Optional clipboard image capture.
/// Polling only reads PNG/TIFF image data; it never writes to the pasteboard or follows URLs.
@MainActor
final class ClipboardWatcher {
    private let source: any ClipboardSource
    private let folder: URL
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastCount: Int?
    private let capture: (any ClipboardAdmission)?
    private var wasPaused = false
    /// The source of the image being delivered. Only meaningful inside `onImage`.
    private(set) var admittedSource: SourceApp?
    static var ownChangeCount = -1

    /// No registered default: a missing preference is false.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: "clipboardEnabled") }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardEnabled") }
    }

    static func recordOwnCopy(changeCount: Int) {
        ownChangeCount = changeCount
    }

    /// The nspasteboard.org markers and the app-specific ones that predate
    /// them. Image, text and link capture all consult this one list.
    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type"
    ].reduce(into: []) { $0.insert(NSPasteboard.PasteboardType($1)) }
    static let maximumDataBytes = 32 * 1024 * 1024
    nonisolated static let maximumPixelCount = 40_000_000

    convenience init(capture: (any ClipboardAdmission)? = nil, onImage: @escaping (URL) -> Void) {
        self.init(source: SystemClipboardSource(), folder: Inbox.folder, capture: capture, onImage: onImage)
    }

    init(source: any ClipboardSource, folder: URL, capture: (any ClipboardAdmission)? = nil, onImage: @escaping (URL) -> Void) {
        self.source = source
        self.folder = folder
        self.capture = capture
        self.onImage = onImage
    }

    func start() {
        guard timer == nil else { return }
        // Enabling or re-enabling never imports the clipboard's previous contents.
        lastCount = source.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        lastCount = nil
        wasPaused = false
    }

    /// Capture continues with the next copy, never the board's current contents.
    func skipCurrent() {
        guard timer != nil else { return }
        lastCount = source.changeCount; wasPaused = false
    }

    /// The one admission path for image, text and link capture. Shelf's own
    /// copies and a skipped copy are dropped before any pasteboard type is
    /// read; private markers and file copies (Finder also advertises a TIFF/PNG
    /// of the file's icon) before any data is read, the source marker included.
    static func admission(of count: Int, in source: any ClipboardSource,
                          capture: (any ClipboardAdmission)?) -> (items: [[NSPasteboard.PasteboardType]], source: SourceApp?)? {
        guard count != ownChangeCount, capture?.skips(changeCount: count) != true else { return nil }
        let items = source.itemTypes
        guard !items.contains(where: { types in
            types.contains(.fileURL) || !privateTypes.isDisjoint(with: types)
        }) else { return nil }
        guard let capture else { return source.changeCount == count ? (items, nil) : nil }
        guard case let .admitted(app) = capture.admit(source: source, items: items),
              source.changeCount == count else { return nil }
        return (items, app)
    }

    /// A paused watcher keeps observing the change count, so nothing copied
    /// during a pause is captured once it ends. A watcher that was not told
    /// the pause ended (`skipCurrent`) cannot date the copy it finds on its
    /// first poll afterwards, and lets that one go too. Returns the new
    /// change count to examine, if any.
    static func changedCount(in source: any ClipboardSource, capture: (any ClipboardAdmission)?,
                             lastCount: inout Int?, wasPaused: inout Bool) -> Int? {
        let paused = capture?.isPaused == true, count = source.changeCount
        if paused || wasPaused { wasPaused = paused; lastCount = count; return nil }
        guard count != lastCount else { return nil }
        lastCount = count
        return count
    }

    /// Internal so tests can advance a synthetic clipboard without waiting for a timer.
    func check() {
        guard timer != nil else { return }
        guard let count = Self.changedCount(in: source, capture: capture, lastCount: &lastCount, wasPaused: &wasPaused),
              let admission = Self.admission(of: count, in: source, capture: capture) else { return }
        let items = admission.items
        admittedSource = admission.source
        defer { admittedSource = nil }

        for (index, types) in items.enumerated() {
            for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
                guard source.changeCount == count else { return }
                let data = source.data(forType: type, at: index)
                guard source.changeCount == count else { return }
                guard let data, let png = Self.validatedPNG(data, type: type) else { continue }
                // Another application can replace the clipboard while we read it.
                guard source.changeCount == count else { return }
                save(png)
                return // A clipboard screenshot is one image, even with multiple representations.
            }
        }
    }

    /// Validate format and resource bounds before decoding. PNG bytes stay unchanged;
    /// TIFF's first frame is converted to PNG using the local system image decoder.
    static func validatedPNG(_ data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard !data.isEmpty, data.count <= maximumDataBytes,
              type == .png || type == .tiff,
              let imageSource = CGImageSourceCreateWithData(data as CFData,
                [kCGImageSourceShouldCache: false] as CFDictionary),
              CGImageSourceGetType(imageSource) as String? == (type == .png ? UTType.png.identifier : UTType.tiff.identifier),
              let properties = CGImageSourceCopyPropertiesAtIndex(imageSource, 0, nil) as? [CFString: Any],
              let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
              let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
              width > 0, height > 0, width <= maximumPixelCount / height else { return nil }

        if type == .png {
            // Decode a small thumbnail to reject a header-only or corrupt PNG.
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 1,
                kCGImageSourceShouldCacheImmediately: true
            ]
            guard CGImageSourceCreateThumbnailAtIndex(imageSource, 0, options as CFDictionary) != nil else { return nil }
            return data
        }

        guard let image = CGImageSourceCreateImageAtIndex(imageSource, 0, nil) else { return nil }
        let result = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(result, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), result.length <= maximumDataBytes else { return nil }
        return result as Data
    }

    private func save(_ data: Data) {
        let name = "Clipboard \(UUID().uuidString).png"
        let url = folder.appendingPathComponent(name)
        var directory: Int32 = -1
        var created = false
        defer { if directory >= 0 { close(directory) } }
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true,
                attributes: [.posixPermissions: 0o700])
            guard folder.resolvingSymlinksInPath().path == folder.standardizedFileURL.path else {
                throw HistoryFiles.Failure.unsafeFile
            }
            // Pin the directory before writing so a substituted symlink cannot
            // redirect private image bytes to another location. O_EXCL also
            // prevents replacing an existing file, even under a hostile race.
            directory = open(folder.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW)
            guard directory >= 0 else { throw HistoryFiles.Failure.unsafeFile }
            var status = stat()
            guard fstat(directory, &status) == 0, status.st_uid == getuid(),
                  fchmod(directory, 0o700) == 0 else { throw HistoryFiles.Failure.unsafeFile }
            let descriptor = openat(directory, name, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW, 0o600)
            guard descriptor >= 0 else { throw HistoryFiles.Failure.unsafeFile }
            created = true
            let output = FileHandle(fileDescriptor: descriptor, closeOnDealloc: true)
            try output.write(contentsOf: data)
            try output.synchronize()
            try output.close()
            guard folder.resolvingSymlinksInPath().path == folder.standardizedFileURL.path,
                  let visible = try? url.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey]),
                  visible.isRegularFile == true, visible.isSymbolicLink != true else {
                throw HistoryFiles.Failure.unsafeFile
            }
            onImage(url)
        } catch {
            if created, directory >= 0 { _ = unlinkat(directory, name, 0) }
            // Avoid logging image bytes, names, paths or clipboard metadata.
            log.error("Could not save a clipboard image")
        }
    }
}
